final _rnd = Random();

List<Mawaz>? _written;

/// مواعظ مكتوبة (آيات وأحاديث وآثار) من مصدر تطبيق نور — assets/data/mawaiz_written.json.
Future<List<Mawaz>> _loadWritten() async {
  if (_written != null) return _written!;
  try {
    final raw = await rootBundle.loadString('assets/data/mawaiz_written.json');
    final m = jsonDecode(raw) as Map<String, dynamic>;
    _written = [
      for (final x in (m['MAWAIZ'] as List).cast<Map<String, dynamic>>())
        Mawaz(
          x['type'] == 'ayah' ? 'ayah' : x['type'] == 'hadith' ? 'hadith' : 'wisdom',
          (x['title'] as String?) ?? '',
          x['type'] == 'ayah' ? '﴿${x['text']}﴾' : (x['text'] as String),
          (x['source'] as String?) ?? '',
          (x['note'] as String?) ?? '',
        ),
    ];
  } catch (_) {
    _written = <Mawaz>[];
  }
  return _written!;
}

/// موعظة عشوائية جديدة: من مواعظ نور المكتوبة، وإن تعذّرت فمن القائمة المضمّنة.
Future<Mawaz> randomMawaz({Mawaz? not}) async {
  final w = await _loadWritten();
  if (w.isNotEmpty) {
    for (var tries = 0; tries < 6; tries++) {
      final m = w[_rnd.nextInt(w.length)];
      if (not == null || m.text != not.text) return m;
    }
    return w.first;
  }
  for (var tries = 0; tries < 6; tries++) {
    final k = _rnd.nextInt(10);
    Mawaz m;
    if (k < 5) {
      m = _hadith[_rnd.nextInt(_hadith.length)];
    } else if (k < 6) {
      m = _wisdom[_rnd.nextInt(_wisdom.length)];
    } else {
      final r = _ayahRefs[_rnd.nextInt(_ayahRefs.length)];
      final ay = await data.ayahs();
      final a = ay.cast<List>().where((x) => x[0] == r.$1 && x[1] == r.$2).firstOrNull;
      if (a == null) continue;
      final name = await data.surahName(r.$1);
      m = Mawaz('ayah', r.$3, '﴿${a[2]}﴾', 'سورة $name · الآية ${r.$2}', r.$4);
    }
    if (not == null || m.text != not.text) return m;
  }
  return _hadith.first;
}
